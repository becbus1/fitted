/**
 * Validate UUID format
 */
function isValidUUID(str: string): boolean {
  const uuidRegex =
    /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
  return uuidRegex.test(str);
}

/**
 * Parse RPC error message to extract error code
 *
 * RPC raises exceptions like: RAISE EXCEPTION 'ALREADY_POSTED'
 * Supabase wraps these in error objects with message containing the code.
 */
function parseRpcError(message: string): ErrorCode {
  // RPC exceptions are formatted as the error code directly
  // or sometimes wrapped in additional text

  const knownCodes: ErrorCode[] = [
    "AUTH_REQUIRED",
    "INVALID_INPUT",
    "CIRCLE_NOT_FOUND",
    "NOT_MEMBER",
    "ALREADY_POSTED",
  ];

  for (const code of knownCodes) {
    if (message.includes(code)) {
      return code;
    }
  }

  return "SERVER_ERROR";
}

/**
 * Map error code to HTTP status
 */
function errorCodeToStatus(code: ErrorCode): number {
  const statusMap: Record<ErrorCode, number> = {
    AUTH_REQUIRED: 401,
    INVALID_INPUT: 400,
    CIRCLE_NOT_FOUND: 404,
    NOT_MEMBER: 403,
    ALREADY_POSTED: 409,
    IMAGE_NOT_FOUND: 400,
    IMAGE_PATH_MISMATCH: 403,
    POST_ID_REUSED: 409,
    SERVER_ERROR: 500,
  };
  return statusMap[code] ?? 500;
}

/**
 * Create error response
 */
function errorResponse(
  code: ErrorCode,
  status: number,
  message?: string
): Response {
  const body: ErrorResponse = {
    error: {
      code,
      ...(message && { message }),
    },
  };

  return new Response(JSON.stringify(body), {
    status,
    headers: {
      ...corsHeaders(),
      "Content-Type": "application/json",
    },
  });
}

/**
 * CORS headers for iOS client
 */
function corsHeaders(): Record<string, string> {
  return {
    "Access-Control-Allow-Origin": "*",
    "Access-Control-Allow-Methods": "POST, OPTIONS",
    "Access-Control-Allow-Headers": "Authorization, Content-Type",
  };
}
