/**
 * Find image in storage by scanning for known extensions
 *
 * WHY: Client uploads with content-type, but we don't know the extension
 * until we check. We try common extensions in order of likelihood.
 */
async function findImageInStorage(
  client: ReturnType<typeof createClient>,
  userId: string,
  postId: string
): Promise<string | null> {
  const extensions = ["jpg", "jpeg", "heic", "png"];
  const basePath = `${userId}/${postId}`;

  for (const ext of extensions) {
    const path = `${basePath}.${ext}`;

    // Check if object exists by attempting to get its metadata
    const { data, error } = await client.storage
      .from(STORAGE_BUCKET)
      .list(userId, {
        search: `${postId}.${ext}`,
        limit: 1,
      });

    if (!error && data && data.length > 0) {
      return path;
    }
  }

  // Also try without extension (in case of MIME-based storage)
  const { data, error } = await client.storage
    .from(STORAGE_BUCKET)
    .list(userId, {
      search: postId,
      limit: 1,
    });

  if (!error && data && data.length > 0) {
    return `${userId}/${data[0].name}`;
  }

  return null;
}

/**
 * Generate signed ImageKit URL for image delivery
 *
 * Uses HMAC-SHA256 signature for URL authentication.
 * Includes transformation parameters for responsive sizing.
 */
function generateSignedImageUrl(
  imagePath: string,
  options: { width: number; height: number }
): string {
  const expiryTimestamp = Math.floor(Date.now() / 1000) + IMAGE_URL_TTL_SECONDS;

  // Transformation string for ImageKit
  const transform = `tr=w-${options.width},h-${options.height},fo-auto,c-at_max`;

  // Base URL without signature
  const baseUrl = `${IMAGEKIT_URL_ENDPOINT}/posts/${imagePath}?${transform}`;

  // Generate signature
  // ImageKit signature = HMAC-SHA256(privateKey, url + expiryTimestamp)
  const signature = generateImageKitSignature(
    `/posts/${imagePath}`,
    transform,
    expiryTimestamp
  );

  return `${baseUrl}&ik-t=${expiryTimestamp}&ik-s=${signature}`;
}

